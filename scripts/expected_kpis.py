"""Compute the headline KPIs in pandas, independent of Power BI.

These are the reconciliation targets: when you build the report, every card
should match the numbers this script prints (written to powerbi/EXPECTED_KPIS.md).

    python scripts/expected_kpis.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "data"


def load():
    t = {n: pd.read_csv(D / f"{n}.csv") for n in
         ["fact_sales", "fact_visits", "fact_targets", "dim_date", "dim_product", "dim_outlet", "dim_territory"]}
    s = t["fact_sales"].merge(t["dim_date"][["date_key", "year", "year_month"]], on="date_key")
    v = t["fact_visits"].merge(t["dim_date"][["date_key", "year"]], on="date_key")
    return t, s, v


def kpis(year: int = 2025) -> dict:
    t, s, v = load()
    cy, py = s[s.year == year], s[s.year == year - 1]
    vy = v[v.year == year]
    net = cy.net_bdt.sum() - cy.returned_bdt.sum()
    net_py = py.net_bdt.sum() - py.returned_bdt.sum()
    tgt = t["fact_targets"][t["fact_targets"].year_month.str.startswith(str(year))].target_bdt.sum()
    visited = vy.visited.sum()
    productive = vy.productive.sum()
    active_outlets = cy.outlet_id.nunique()
    by_cat = (cy.merge(t["dim_product"], on="sku").groupby("category").net_bdt.sum() / cy.net_bdt.sum() * 100).round(1)
    terr = (cy.merge(t["dim_outlet"], on="outlet_id").merge(t["dim_territory"], on="territory_id")
              .groupby("division").net_bdt.sum().sort_values(ascending=False))
    orders = cy.visit_id.nunique()
    dec = cy[cy.year_month == f"{year}-12"]
    nd_sku = (dec.groupby("sku").outlet_id.nunique() / len(t["dim_outlet"]) * 100).round(1)
    return {
        "Net Sales (BDT)": round(net),
        "Net Sales LY (BDT)": round(net_py),
        "Net Sales YoY %": round((net / net_py - 1) * 100, 1),
        "Target (BDT)": round(tgt),
        "Target Achievement %": round(net / tgt * 100, 1),
        "Visits (completed)": int(visited),
        "Strike Rate %": round(productive / visited * 100, 1),
        "Active Outlets": int(active_outlets),
        "Numeric Distribution %, Dec 2025": round(dec.outlet_id.nunique() / len(t["dim_outlet"]) * 100, 1),
        "Avg Drop Size (BDT per order)": round(cy.net_bdt.sum() / orders),
        "Lines per Productive Call": round(len(cy) / orders, 2),
        "Return Rate %": round(cy.returned_bdt.sum() / cy.net_bdt.sum() * 100, 2),
        "GPS-verified Visits %": round(vy[vy.visited == 1].gps_verified.mean() * 100, 1),
        "_category_share": by_cat.to_dict(),
        "_division_sales": terr.round().astype(int).to_dict(),
        "_nd_sku": nd_sku.to_dict(),
    }


def main():
    k = kpis()
    lines = ["# Expected KPI values (calendar year 2025)", "",
             "Generated by `scripts/expected_kpis.py` directly from the CSVs. Your Power BI cards, filtered to 2025, "
             "should show these numbers. If one doesn't match, the measure or a relationship is wrong.", "",
             "| Measure | Expected value |", "|---|---:|"]
    for name, val in k.items():
        if name.startswith("_"):
            continue
        lines.append(f"| {name} | {val:,} |")
    lines += ["", "**Net sales share by category (before returns)**", "", "| Category | Share |", "|---|---:|"]
    lines += [f"| {c} | {v}% |" for c, v in sorted(k["_category_share"].items(), key=lambda x: -x[1])]
    lines += ["", "**Net sales by division (before returns, BDT)**", "", "| Division | Net sales |", "|---|---:|"]
    lines += [f"| {d} | {v:,} |" for d, v in k["_division_sales"].items()]
    lines += ["", "**Numeric distribution by SKU, Dec 2025** (share of all outlets that bought the SKU that month)", "",
              "| SKU | Numeric distribution |", "|---|---:|"]
    lines += [f"| {sku} | {v}% |" for sku, v in k["_nd_sku"].items()]
    (ROOT / "powerbi" / "EXPECTED_KPIS.md").write_text("\n".join(lines) + "\n")
    for name, val in k.items():
        if not name.startswith("_"):
            print(f"{name:32} {val:,}")


if __name__ == "__main__":
    main()
